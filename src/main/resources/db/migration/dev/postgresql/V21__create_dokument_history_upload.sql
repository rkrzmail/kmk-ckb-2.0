ALTER TABLE public.mst_file_type
    ADD COLUMN IF NOT EXISTS is_esign boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.dokument_history_upload (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    financing_hdr_code uuid NOT NULL REFERENCES public.financing_hdr(financing_hdr_code),
    file_type_code varchar(20) NOT NULL REFERENCES public.mst_file_type(file_type_code),
    file_path varchar(8000) NOT NULL,
    file_name varchar(500) NOT NULL,
    content_type varchar(500) NOT NULL,
    expired_date date,
    notes text,
    uploaded_by varchar(50) NOT NULL,
    uploaded_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dokument_history_upload_latest
    ON public.dokument_history_upload(financing_hdr_code, file_type_code, uploaded_at DESC, id DESC);
